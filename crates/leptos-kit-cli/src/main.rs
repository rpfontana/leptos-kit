mod registry;

use registry::{
    BASE_COLORS, COMPONENTS, Component, ICON_LIBRARIES, ICONS, SHARED, STRUCTURE, STYLES, THEME,
    UTILS,
};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

type Result<T = (), E = Box<dyn std::error::Error>> = std::result::Result<T, E>;

const CONFIG: &str = "leptos-kit.toml";
const GENERATED: &str = "/* generated by leptos-kit, this file will be overwritten on every `apply` */\n";
const CUSTOM: &str = "/* your custom css rules go here */\n";
const CRATES: &[&str] = &[
    "leptos-kit-primitives",
    "leptos-kit-macros",
    "leptos-kit-icons",
];

const USAGE: &str = "usage:
  leptos-kit init [--style nova[,lyra…]] [--base-color neutral[,stone…]] [--icons lucide]
                  [--components src/ui] [--css style/leptos-kit] [--kit <path to the leptos-kit repo>]
  leptos-kit add <component>... [--overwrite]
  leptos-kit list";

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let result = match args.first().map(String::as_str) {
        Some("init") => init(&args[1..]),
        Some("add") => add(&args[1..]),
        Some("list") => {
            list();
            Ok(())
        }
        None | Some("help" | "--help") => {
            println!("{USAGE}");
            Ok(())
        }
        Some(other) => Err(format!("unknown command `{other}`\n\n{USAGE}").into()),
    };
    if let Err(error) = result {
        eprintln!("error: {error}");
        std::process::exit(1);
    }
}

struct Config {
    styles: Vec<String>,
    base_colors: Vec<String>,
    icons: String,
    components: PathBuf,
    css: PathBuf,
}

impl Config {
    fn read() -> Result<Self> {
        let text = fs::read_to_string(CONFIG)
            .map_err(|_| format!("no {CONFIG} here, run `leptos-kit init` first"))?;
        let value = |key: &str| {
            text.lines()
                .filter_map(|line| line.split_once('='))
                .find(|(name, _)| name.trim() == key)
                .map(|(_, value)| value.trim().to_string())
        };
        let required = |key: &str| -> Result<String> {
            value(key)
                .map(|value| value.trim_matches('"').to_string())
                .ok_or_else(|| format!("{CONFIG} has no `{key}`").into())
        };
        let list = |key: &str| -> Result<Vec<String>> {
            value(key)
                .map(|value| names(value.trim_start_matches('[').trim_end_matches(']')))
                .ok_or_else(|| format!("{CONFIG} has no `{key}`").into())
        };
        let config = Self {
            styles: list("styles")?,
            base_colors: list("base-colors")?,
            icons: required("icons")?,
            components: required("components")?.into(),
            css: required("css")?.into(),
        };
        config.check()?;
        Ok(config)
    }

    fn write(&self) -> Result {
        let list = |names: &[String]| {
            let quoted: Vec<String> = names.iter().map(|name| format!("\"{name}\"")).collect();
            format!("[{}]", quoted.join(", "))
        };
        fs::write(
            CONFIG,
            format!(
                "styles = {}\nbase-colors = {}\nicons = \"{}\"\ncomponents = \"{}\"\ncss = \"{}\"\n",
                list(&self.styles),
                list(&self.base_colors),
                self.icons,
                slashes(&self.components),
                slashes(&self.css),
            ),
        )?;
        Ok(())
    }

    fn check(&self) -> Result {
        if self.styles.is_empty() || self.base_colors.is_empty() {
            return Err("at least one style and one base colour".into());
        }
        for style in &self.styles {
            pick(STYLES, style, "style")?;
        }
        for color in &self.base_colors {
            pick(BASE_COLORS, color, "base colour")?;
        }
        if !ICON_LIBRARIES.contains(&self.icons.as_str()) {
            return Err(format!(
                "unknown icon library `{}`, expected one of {ICON_LIBRARIES:?}",
                self.icons
            )
            .into());
        }
        Ok(())
    }

    fn sheets(&self) -> Vec<(&str, &'static str)> {
        self.styles
            .iter()
            .filter_map(|name| Some((name.as_str(), pick(STYLES, name, "style").ok()?)))
            .collect()
    }
}

fn init(args: &[String]) -> Result {
    let config = Config {
        styles: names(option(args, "--style").unwrap_or("nova")),
        base_colors: names(option(args, "--base-color").unwrap_or("neutral")),
        icons: option(args, "--icons").unwrap_or("lucide").into(),
        components: option(args, "--components").unwrap_or("src/ui").into(),
        css: option(args, "--css").unwrap_or("style/leptos-kit").into(),
    };
    config.check()?;
    if Path::new(CONFIG).exists() {
        return Err(format!("{CONFIG} already exists").into());
    }

    match option(args, "--kit") {
        Some(kit) => {
            for name in CRATES {
                let path = Path::new(kit).join("crates").join(name);
                let status = Command::new("cargo")
                    .arg("add")
                    .arg("--path")
                    .arg(&path)
                    .status()?;
                if !status.success() {
                    return Err(format!("`cargo add --path {}` failed", slashes(&path)).into());
                }
            }
        }
        None => println!("add the dependencies: {}", CRATES.join(", ")),
    }

    fs::create_dir_all(&config.css)?;
    for (name, css) in SHARED {
        fs::write(config.css.join(name), format!("{GENERATED}{css}"))?;
    }
    fs::write(
        config.css.join("theme.css"),
        format!("{GENERATED}{}", unheaded(THEME)),
    )?;
    fs::write(config.css.join("colors.css"), colors(&config.base_colors))?;
    write_new(&config.css.join("ui.css"), GENERATED)?;
    write_new(&config.css.join("custom.css"), CUSTOM)?;
    fs::write(
        config.css.join("index.css"),
        format!(
            "{GENERATED}@import \"./tw-animate.css\";\n@import \"./shadcn-tailwind.css\";\n\
             @import \"./theme.css\";\n@import \"./colors.css\";\n@import \"./ui.css\";\n\
             @import \"./custom.css\";\n"
        ),
    )?;

    fs::create_dir_all(&config.components)?;
    write_new(&config.components.join("utils.rs"), UTILS)?;
    write_new(&config.components.join("mod.rs"), "mod utils;\n")?;
    config.write()?;

    let module = config
        .components
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("ui");
    println!(
        "\nleptos-kit is set up, three things left to you:\n\
         - `mod {module};` in the crate root\n\
         - `@import \"…/{}/index.css\";` in the Tailwind entry, after tailwindcss\n\
         - `leptos-kit-primitives/ssr` and `leptos-kit-icons/ssr` in the ssr feature, `/hydrate` in hydrate",
        slashes(&config.css),
    );
    classes(&config);
    Ok(())
}

fn classes(config: &Config) {
    if config.styles.len() > 1 {
        println!(
            "several styles: `class=\"style-{}\"` on <html>, or on any element, picks the one inside it",
            config.styles[0]
        );
    }
    if let [first, others @ ..] = config.base_colors.as_slice()
        && !others.is_empty()
    {
        println!(
            "{first} is the default colour, `class=\"base-color-{}\"` on <html> or any element switches what is inside it",
            others[0]
        );
    }
}

fn add(args: &[String]) -> Result {
    let config = Config::read()?;
    let overwrite = args.iter().any(|arg| arg == "--overwrite");
    let names: Vec<&str> = args
        .iter()
        .map(String::as_str)
        .filter(|arg| !arg.starts_with("--"))
        .collect();
    if names.is_empty() {
        return Err("which components? `leptos-kit list` shows them".into());
    }
    let mut order = Vec::new();
    for name in names {
        resolve(name, &mut order)?;
    }

    let sheets = config.sheets();
    let icons = icons(&config.icons);
    fs::create_dir_all(&config.components)?;
    fs::create_dir_all(&config.css)?;
    write_new(&config.components.join("utils.rs"), UTILS)?;
    let modules_path = config.components.join("mod.rs");
    let mut modules = fs::read_to_string(&modules_path).unwrap_or_else(|_| "mod utils;\n".into());
    let ui_path = config.css.join("ui.css");
    let mut ui = fs::read_to_string(&ui_path).unwrap_or_else(|_| GENERATED.into());

    for component in order {
        let file = config.components.join(format!("{}.rs", component.name));
        if file.exists() && !overwrite {
            println!("kept {}", slashes(&file));
        } else {
            fs::write(
                &file,
                resolve_icons(component.source, &config.icons, &icons),
            )?;
            println!("wrote {}", slashes(&file));
        }
        let module = format!("pub mod {};", component.name);
        if !modules.lines().any(|line| line.trim() == module) {
            modules.push_str(&module);
            modules.push('\n');
        }
        match section(&ui, component.name) {
            Some(range) if overwrite => ui.replace_range(range, &css(component, &sheets)),
            Some(_) => {}
            None => ui.push_str(&css(component, &sheets)),
        }
    }
    fs::write(&modules_path, modules)?;
    fs::write(&ui_path, ui)?;
    Ok(())
}

fn list() {
    for component in COMPONENTS {
        match component.dependencies {
            [] => println!("{}", component.name),
            dependencies => println!("{} (with {})", component.name, dependencies.join(", ")),
        }
    }
}

// dependencies first, each once
fn resolve(name: &str, order: &mut Vec<&'static Component>) -> Result {
    let component = registry::component(name)
        .ok_or_else(|| format!("no component `{name}`, `leptos-kit list` shows them"))?;
    if order.iter().any(|done| done.name == name) {
        return Ok(());
    }
    for dependency in component.dependencies {
        resolve(dependency, order)?;
    }
    order.push(component);
    Ok(())
}

fn css(component: &Component, sheets: &[(&str, &str)]) -> String {
    let mut out = format!("/* {} */\n", component.name);
    let hooks = hooks(component.source);
    let base = match sheets {
        [(_, sheet)] => rules(sheet, &hooks),
        _ => sheets
            .iter()
            .map(|(name, sheet)| (name, rules(sheet, &hooks)))
            .filter(|(_, rules)| !rules.is_empty())
            .map(|(name, rules)| {
                let nested: String = rules.lines().map(|line| format!("  {line}\n")).collect();
                format!("  .style-{name} {{\n{nested}  }}\n")
            })
            .collect(),
    };
    if !base.is_empty() {
        out.push_str(&format!("@layer base {{\n{base}}}\n"));
    }
    let structure = rules(STRUCTURE, &hooks);
    if !structure.is_empty() {
        out.push_str(&format!("@layer components {{\n{structure}}}\n"));
    }
    if let Some(own) = component.css {
        out.push_str(own);
    }
    out
}

// a section runs to the next component's marker, its own comments don't end it
fn section(css: &str, name: &str) -> Option<std::ops::Range<usize>> {
    let start = marker(css, name)?;
    let after = start + 1;
    let end = COMPONENTS
        .iter()
        .filter_map(|component| marker(&css[after..], component.name))
        .min()
        .map_or(css.len(), |at| after + at);
    Some(start..end)
}

fn marker(css: &str, name: &str) -> Option<usize> {
    let marker = format!("/* {name} */");
    css.match_indices(&marker)
        .map(|(at, _)| at)
        .find(|&at| at == 0 || css[..at].ends_with('\n'))
}

// `cn-button-size-{size}` leaves the prefix `cn-button-size-`
fn hooks(source: &str) -> Vec<&str> {
    source
        .match_indices("cn-")
        .map(|(at, _)| {
            let rest = &source[at..];
            let end = rest
                .find(|c: char| !c.is_ascii_alphanumeric() && c != '-')
                .unwrap_or(rest.len());
            &rest[..end]
        })
        .collect()
}

// the style sheets hold one rule per hook, two spaces in, under a single block
fn rules(css: &str, hooks: &[&str]) -> String {
    let mut out = String::new();
    let mut taking = false;
    for line in css.lines() {
        if line.starts_with("  .") && line.ends_with('{') {
            let hook: String = line[3..]
                .chars()
                .take_while(|c| c.is_ascii_alphanumeric() || *c == '-')
                .collect();
            taking = hooks.iter().any(|known| match known.strip_suffix('-') {
                Some(_) => hook.starts_with(known),
                None => hook == *known,
            });
        }
        if taking {
            out.push_str(line);
            out.push('\n');
            if line == "  }" {
                taking = false;
            }
        }
    }
    out
}

fn icons(library: &str) -> Vec<(String, String)> {
    let prefix = format!("pub use crate::{library}::");
    let mut icons: Vec<(String, String)> = ICONS
        .lines()
        .filter_map(|line| line.trim().strip_prefix(prefix.as_str()))
        .filter_map(|rest| rest.trim_end_matches(';').split_once(" as "))
        .map(|(glyph, name)| (glyph.to_string(), name.to_string()))
        .collect();
    icons.sort_by_key(|(_, name)| std::cmp::Reverse(name.len()));
    icons
}

fn resolve_icons(source: &str, library: &str, icons: &[(String, String)]) -> String {
    let mut out = source.replace(
        "use leptos_kit_icons::{Icon, semantic};",
        &format!("use leptos_kit_icons::{{Icon, {library}}};"),
    );
    for (glyph, name) in icons {
        out = out.replace(&format!("semantic::{name}"), &format!("{library}::{glyph}"));
    }
    out
}

fn pick(list: &'static [(&str, &str)], name: &str, what: &str) -> Result<&'static str> {
    list.iter()
        .find(|(known, _)| *known == name)
        .map(|(_, value)| *value)
        .ok_or_else(|| {
            let known: Vec<&str> = list.iter().map(|(known, _)| *known).collect();
            format!("unknown {what} `{name}`, expected one of {known:?}").into()
        })
}

fn option<'a>(args: &'a [String], name: &str) -> Option<&'a str> {
    args.iter()
        .position(|arg| arg == name)
        .and_then(|at| args.get(at + 1))
        .map(String::as_str)
}

fn write_new(path: &Path, contents: &str) -> Result {
    if !path.exists() {
        fs::write(path, contents)?;
    }
    Ok(())
}

// the first colour is the default, the others apply inside their class
fn colors(names: &[String]) -> String {
    let mut out = String::from(GENERATED);
    for (i, name) in names.iter().enumerate() {
        let Ok(sheet) = pick(BASE_COLORS, name, "base colour") else {
            continue;
        };
        let sheet = unheaded(sheet);
        if i == 0 {
            out.push_str(sheet);
            continue;
        }
        let class = format!(".base-color-{name}");
        out.push('\n');
        out.push_str(
            &sheet
                .replace(":root {", &format!("{class} {{"))
                .replace(".dark {", &format!(".dark {class},\n{class}.dark {{")),
        );
    }
    out
}

// nova, lyra or ["nova", "lyra"]
fn names(list: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for name in list.split(',').map(|name| name.trim().trim_matches('"')) {
        if !name.is_empty() && !out.iter().any(|known| known == name) {
            out.push(name.to_string());
        }
    }
    out
}

// the repo's header is about xtask, not the app
fn unheaded(css: &str) -> &str {
    if !css.starts_with("/* @generated") {
        return css;
    }
    css.split_once('\n')
        .map_or("", |(_, rest)| rest.trim_start_matches(['\r', '\n']))
}

fn slashes(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}
