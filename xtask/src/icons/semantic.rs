//! names carry the usage site rather than the glyph, because the glyph isn't
//! stable across libraries: shadcn draws the select trigger with lucide's
//! `ChevronDownIcon` but with tabler's `IconSelector`, while the accordion uses
//! tabler's `IconChevronDown` for the same lucide icon

use super::Library;
use crate::{Result, workspace_root};
use serde_json::Value;
use std::fmt::Write as _;
use std::fs;

pub fn generate(libraries: &[&Library]) -> Result {
    let data = fs::read_to_string(workspace_root().join("xtask/data/shadcn-icons.json"))?;
    let data: Value = serde_json::from_str(&data)?;
    let source = data["source"].as_str().unwrap_or("unknown");
    let icons = data["icons"]
        .as_object()
        .ok_or("shadcn-icons.json has no `icons` object")?;

    let mut out = String::new();
    writeln!(
        out,
        "// @generated by `cargo xtask icons`, do not edit\n\
         //! the icons leptos-kit uses internally, named by where they are used\n\
         //!\n\
         //! from the `<IconPlaceholder>` elements of {source}",
    )?;

    for (index, library) in libraries.iter().enumerate() {
        let earlier: Vec<String> = libraries[..index]
            .iter()
            .map(|l| format!("feature = {:?}", l.name))
            .collect();
        let cfg = if earlier.is_empty() {
            format!("#[cfg(feature = {:?})]", library.name)
        } else {
            format!(
                "#[cfg(all(feature = {:?}, not(any({}))))]",
                library.name,
                earlier.join(", ")
            )
        };

        let mut uses: Vec<String> = Vec::new();
        for (canonical, icon) in icons {
            for component in icon["users"].as_array().into_iter().flatten() {
                let component = component.as_str().unwrap_or_default();
                let glyph = resolve(&data, canonical, library.name, component)?;
                uses.push(format!(
                    "    pub use crate::{module}::{glyph} as {key};",
                    module = library.name,
                    glyph = constant_name(&glyph),
                    key = key_name(component, canonical),
                ));
            }
        }
        uses.sort();

        writeln!(
            out,
            "\n{cfg}\nmod resolved {{\n{uses}\n}}\n\n{cfg}\npub use resolved::*;",
            uses = uses.join("\n"),
        )?;
    }

    let target = workspace_root().join("crates/leptos-kit-icons/src/semantic.rs");
    fs::write(&target, out)?;
    println!(
        "semantic: {} icons across {} components -> {}",
        icons.len(),
        icons
            .values()
            .flat_map(|icon| icon["users"].as_array().into_iter().flatten())
            .filter_map(|c| c.as_str())
            .collect::<std::collections::BTreeSet<_>>()
            .len(),
        target
            .strip_prefix(workspace_root())
            .unwrap_or(&target)
            .display(),
    );
    Ok(())
}

/// the per-component override when shadcn has one, otherwise the library's
/// usual name for that icon
fn resolve(data: &Value, canonical: &str, library: &str, component: &str) -> Result<String> {
    let override_ = data["conflicts"]
        .as_array()
        .into_iter()
        .flatten()
        .find(|conflict| {
            conflict["lucide"] == canonical
                && conflict["library"] == library
                && conflict["component"] == component
        })
        .and_then(|conflict| conflict["second"].as_str());

    if let Some(glyph) = override_ {
        return Ok(upstream_name(glyph));
    }
    data["icons"][canonical][library]
        .as_str()
        .map(upstream_name)
        .ok_or_else(|| format!("{canonical} has no {library} name").into())
}

/// `ChevronDownIcon` -> `chevron-down`, `Loader2Icon` -> `loader-2`
fn upstream_name(react_name: &str) -> String {
    let name = react_name.strip_suffix("Icon").unwrap_or(react_name);
    let chars: Vec<char> = name.chars().collect();
    let mut out = String::new();
    for (index, &char) in chars.iter().enumerate() {
        let previous = index.checked_sub(1).map(|i| chars[i]);
        let boundary = match previous {
            None => false,
            Some(previous) => {
                (char.is_ascii_uppercase() && !previous.is_ascii_uppercase())
                    || (char.is_ascii_digit() && previous.is_ascii_alphabetic())
                    || (char.is_ascii_uppercase()
                        && previous.is_ascii_uppercase()
                        && chars.get(index + 1).is_some_and(char::is_ascii_lowercase))
            }
        };
        if boundary {
            out.push('-');
        }
        out.extend(char.to_lowercase());
    }
    out
}

/// `select` + `ChevronDownIcon` -> `SELECT_CHEVRON_DOWN`
fn key_name(component: &str, canonical: &str) -> String {
    format!(
        "{}_{}",
        constant_name(component),
        constant_name(&upstream_name(canonical))
    )
}

fn constant_name(name: &str) -> String {
    name.to_uppercase().replace('-', "_")
}
