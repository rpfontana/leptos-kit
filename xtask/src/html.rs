//! reads the attribute index of the whatwg standard, which leaves the obsolete ones out

use crate::{Result, download, rustfmt, workspace_root};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;

const REVIEW_DRAFT: &str = "2026-07";

/// the globals worth a prop, the rest go through `attr:`
const GLOBALS: &[&str] = &["class", "id", "style", "title", "tabindex"];

struct Attribute {
    name: String,
    kind: &'static str,
    doc: String,
}

pub fn run(args: &[String]) -> Result {
    if !args.is_empty() {
        return Err("`html` takes no arguments".into());
    }

    let url = format!(
        "https://raw.githubusercontent.com/whatwg/html/main/review-drafts/{REVIEW_DRAFT}.wattsi"
    );
    let source = fs::read_to_string(download(
        &url,
        &format!("whatwg-html-review-draft-{REVIEW_DRAFT}.wattsi"),
    )?)?;

    let mut elements: BTreeMap<String, Vec<Attribute>> = BTreeMap::new();
    for row in rows(table(&source, "List of elements")?) {
        for name in codes(
            cells(row).first().ok_or("empty row in the element index")?,
            "<code>",
        ) {
            elements.entry(name).or_default();
        }
    }

    let mut global = Vec::new();
    let mut dashed = Vec::new();
    let attributes = table(
        &source,
        "List of attributes (excluding event handler content attributes)",
    )?;
    for row in rows(attributes) {
        let [name, owners, description, value] = cells(row)[..] else {
            return Err(format!("unexpected attribute row: {row}").into());
        };
        let name = text(name);
        if name.contains('-') {
            // a dashed key never becomes a prop: Leptos spreads it on its own
            dashed.push(name);
            continue;
        }
        let attribute = || Attribute {
            name: name.clone(),
            kind: kind(&text(value)),
            doc: doc(&text(description)),
        };

        if owners.contains(">HTML elements</span>") {
            if GLOBALS.contains(&name.as_str()) {
                global.push(attribute());
            }
            continue;
        }
        for owner in codes(owners, "<code data-x=\"attr-") {
            let Some(list) = elements.get_mut(&owner) else {
                return Err(
                    format!("`{name}` belongs to `{owner}`, which isn't an element").into(),
                );
            };
            if !list.iter().any(|a| a.name == name) {
                list.push(attribute());
            }
        }
    }

    for name in GLOBALS {
        if !global.iter().any(|a| a.name == *name) {
            return Err(format!("global attribute `{name}` is gone from the standard").into());
        }
    }
    // not in the HTML standard, but callers set it all the time
    global.push(Attribute {
        name: "role".into(),
        kind: "Text",
        doc: "the element's ARIA role".into(),
    });
    global.sort_by(|a, b| a.name.cmp(&b.name));
    for list in elements.values_mut() {
        list.sort_by(|a, b| a.name.cmp(&b.name));
    }

    let mut out = String::with_capacity(64 * 1024);
    writeln!(
        out,
        "// @generated by `cargo xtask html`, do not edit\n\
         //! html attributes by element, whatwg review draft {REVIEW_DRAFT}, descriptions © WHATWG, CC BY 4.0\n\
         \n\
         use crate::{{Attribute, Kind}};\n\
         \n\
         pub static GLOBAL: &[Attribute] = &[",
    )?;
    for attribute in &global {
        write_attribute(&mut out, attribute, "    ")?;
    }
    writeln!(
        out,
        "];\n\npub static ELEMENTS: &[(&str, &[Attribute])] = &["
    )?;
    for (element, attributes) in &elements {
        if attributes.is_empty() {
            writeln!(out, "    ({element:?}, &[]),")?;
            continue;
        }
        writeln!(out, "    (\n        {element:?},\n        &[")?;
        for attribute in attributes {
            write_attribute(&mut out, attribute, "            ")?;
        }
        writeln!(out, "        ],\n    ),")?;
    }
    writeln!(out, "];")?;

    let target = workspace_root()
        .join("crates")
        .join("leptos-kit-macros")
        .join("src")
        .join("html.rs");
    fs::write(&target, out)?;
    rustfmt(&target)?;
    println!(
        "html: {} elements, {} element attributes, {} globals -> {}",
        elements.len(),
        elements.values().map(Vec::len).sum::<usize>(),
        global.len(),
        target
            .strip_prefix(workspace_root())
            .unwrap_or(&target)
            .display(),
    );
    println!("html: left to the spread: {}", dashed.join(", "));
    Ok(())
}

fn write_attribute(out: &mut String, attribute: &Attribute, indent: &str) -> Result {
    writeln!(
        out,
        "{indent}Attribute {{\n\
         {indent}    name: {name:?},\n\
         {indent}    kind: Kind::{kind},\n\
         {indent}    doc: {doc:?},\n\
         {indent}}},",
        name = attribute.name,
        kind = attribute.kind,
        doc = attribute.doc,
    )?;
    Ok(())
}

/// only what a call site writes as a literal gets a type, the rest is a string
fn kind(value: &str) -> &'static str {
    let value = value.trim_end_matches('*');
    if value.starts_with("Boolean attribute") {
        "Bool"
    } else if value.starts_with("Valid integer") {
        "Int"
    } else if value.starts_with("Valid non-negative integer") {
        "UInt"
    } else if value == "Valid floating-point number" {
        "Float"
    } else {
        "Text"
    }
}

/// lowercased to read as the rest of the docs, unless it opens with an acronym
fn doc(description: &str) -> String {
    let description = description.trim_end_matches('.');
    let mut chars = description.chars();
    match (chars.next(), chars.next()) {
        (Some(first), Some(second)) if second.is_lowercase() => {
            first.to_lowercase().collect::<String>() + &description[first.len_utf8()..]
        }
        _ => description.to_string(),
    }
}

fn table<'a>(source: &'a str, caption: &str) -> Result<&'a str> {
    let start = source
        .find(&format!("<caption>{caption}</caption>"))
        .ok_or_else(|| format!("no table captioned `{caption}`"))?;
    let rest = &source[start..];
    let end = rest.find("</table>").ok_or("unterminated table")?;
    let body = rest[..end].find("<tbody>").ok_or("table without a body")?;
    Ok(&rest[body..end])
}

fn rows(table: &str) -> impl Iterator<Item = &str> {
    table.split("<tr>").skip(1)
}

/// only the element index closes its cells, so split on the opening tags
fn cells(row: &str) -> Vec<&str> {
    let mut starts: Vec<usize> = row
        .match_indices("<th>")
        .chain(row.match_indices("<td>"))
        .map(|(i, _)| i + 4)
        .collect();
    starts.sort_unstable();
    starts
        .iter()
        .enumerate()
        .map(|(n, &start)| {
            let end = starts.get(n + 1).map_or(row.len(), |next| next - 4);
            &row[start..end]
        })
        .collect()
}

/// matching on `data-x` skips the bare `<code>` in "`source` (in `picture`)"
fn codes(cell: &str, open: &str) -> Vec<String> {
    cell.match_indices(open)
        .filter_map(|(i, _)| {
            let rest = &cell[i..];
            let start = rest.find('>')? + 1;
            let end = rest.find("</code>")?;
            Some(rest[start..end].to_string())
        })
        .collect()
}

fn text(html: &str) -> String {
    let mut out = String::with_capacity(html.len());
    let mut rest = html;
    while let Some(start) = rest.find(['<', '&']) {
        out.push_str(&rest[..start]);
        rest = &rest[start..];
        if let Some(comment) = rest.strip_prefix("<!--") {
            rest = comment.find("-->").map_or("", |end| &comment[end + 3..]);
        } else if rest.starts_with('<') {
            rest = rest.find('>').map_or("", |end| &rest[end + 1..]);
        } else {
            let end = rest.find(';').unwrap_or(0);
            out.push_str(match &rest[..=end] {
                "&amp;" => "&",
                "&lt;" => "<",
                "&gt;" => ">",
                "&quot;" => "\"",
                "&nbsp;" => " ",
                "&mdash;" => "—",
                "&ndash;" => "–",
                other => other,
            });
            rest = &rest[end + 1..];
        }
    }
    out.push_str(rest);
    out.split_whitespace().collect::<Vec<_>>().join(" ")
}
