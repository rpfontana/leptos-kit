pub struct Icon {
    pub name: String,
    pub body: String,
}

pub struct Style {
    pub view_box: &'static str,
    pub fill: &'static str,
    pub stroke: &'static str,
    pub stroke_width: &'static str,
    pub stroke_linecap: &'static str,
    pub stroke_linejoin: &'static str,
}

pub enum Data {
    Dir {
        path: &'static str,
        extension: &'static str,
    },
}

pub struct Library {
    // shadcn's name, also the cargo feature and the module
    pub name: &'static str,
    // tabler's `IconChevronDown`, lucide's `ChevronDownIcon`
    pub react_prefix: &'static str,
    pub react_suffix: &'static str,
    pub package: &'static str,
    pub version: &'static str,
    pub data: Data,
    pub licence_path: &'static str,
    pub licence: &'static str,
    pub style: Style,
    pub parse: fn(&[(String, String)]) -> Result<Vec<Icon>>,
}

static LIBRARIES: &[&Library] = &[&lucide::LIBRARY, &tabler::LIBRARY, &hugeicons::LIBRARY];

pub fn run(args: &[String]) -> Result {
    let requested: Vec<&Library> = match args.first() {
        None => LIBRARIES.to_vec(),
        Some(name) => match LIBRARIES.iter().find(|l| l.name == name) {
            Some(library) => vec![*library],
            None => {
                let known: Vec<&str> = LIBRARIES.iter().map(|l| l.name).collect();
                return Err(
                    format!("unknown icon library `{name}`; known: {}", known.join(", ")).into(),
                );
            }
        },
    };

    for library in requested {
        generate(library)?;
    }
    semantic::generate(LIBRARIES)?;
    Ok(())
}

fn generate(library: &Library) -> Result {
    let package = fetch(library)?;

    let licence = package
        .iter()
        .find(|(name, _)| name == library.licence_path)
        .ok_or_else(|| format!("{} has no {}", library.package, library.licence_path))?;
    let licence_file = icons_crate()
        .join("licences")
        .join(format!("{}.txt", library.name));
    fs::create_dir_all(licence_file.parent().unwrap())?;
    fs::write(&licence_file, &licence.1)?;

    let Data::Dir { path, extension } = library.data;
    let files: Vec<(String, String)> = package
        .into_iter()
        .filter(|(name, _)| {
            name.strip_prefix(path)
                .is_some_and(|rest| rest.ends_with(extension) && !rest.contains('/'))
        })
        .map(|(name, contents)| {
            let name = name[path.len()..].trim_end_matches(extension).to_string();
            (name, contents)
        })
        .collect();

    let mut icons = (library.parse)(&files)?;
    icons.sort_by(|a, b| a.name.cmp(&b.name));

    let mut out = String::with_capacity(icons.len() * 200);
    writeln!(
        out,
        "// @generated by `cargo xtask icons` from `{package}` {version}, do not edit\n\
         // {licence} licensed, see `licences/{name}.txt`\n\
         \n\
         use crate::{{IconData, IconStyle}};\n\
         \n\
         pub static STYLE: IconStyle = IconStyle {{\n\
         \x20   view_box: {view_box:?},\n\
         \x20   fill: {fill:?},\n\
         \x20   stroke: {stroke:?},\n\
         \x20   stroke_width: {stroke_width:?},\n\
         \x20   stroke_linecap: {stroke_linecap:?},\n\
         \x20   stroke_linejoin: {stroke_linejoin:?},\n\
         }};",
        package = library.package,
        version = library.version,
        licence = library.licence,
        name = library.name,
        view_box = library.style.view_box,
        fill = library.style.fill,
        stroke = library.style.stroke,
        stroke_width = library.style.stroke_width,
        stroke_linecap = library.style.stroke_linecap,
        stroke_linejoin = library.style.stroke_linejoin,
    )?;

    for icon in &icons {
        if icon.body.contains("\"#") {
            return Err(format!("icon `{}` would break the raw string", icon.name).into());
        }
        writeln!(
            out,
            "\npub const {constant}: IconData = IconData {{\n\
             \x20   style: &STYLE,\n\
             \x20   body: r#\"{body}\"#,\n\
             }};",
            constant = constant_name(&icon.name),
            body = icon.body,
        )?;
    }

    let target = icons_crate()
        .join("src")
        .join(format!("{}.rs", library.name));
    fs::write(&target, out)?;
    println!(
        "{}: {} icons -> {} ({} KiB)",
        library.name,
        icons.len(),
        target
            .strip_prefix(workspace_root())
            .unwrap_or(&target)
            .display(),
        fs::metadata(&target)?.len() / 1024,
    );
    Ok(())
}

// paths come back without the leading `package/`
fn fetch(library: &Library) -> Result<Vec<(String, String)>> {
    let file_name = format!(
        "{}-{}.tgz",
        library.package.replace('/', "-"),
        library.version
    );
    let url = format!(
        "https://registry.npmjs.org/{package}/-/{base}-{version}.tgz",
        package = library.package,
        base = library.package.rsplit('/').next().unwrap(),
        version = library.version,
    );
    let cached = download(&url, &file_name)?;

    let tarball = flate2::read::GzDecoder::new(fs::File::open(&cached)?);
    let mut archive = tar::Archive::new(tarball);
    let mut entries = Vec::new();
    for entry in archive.entries()? {
        let mut entry = entry?;
        let path = entry.path()?.to_string_lossy().replace('\\', "/");
        let Some(path) = path.strip_prefix("package/").map(str::to_string) else {
            continue;
        };
        let mut contents = String::new();
        // skips fonts and images
        if entry.read_to_string(&mut contents).is_ok() {
            entries.push((path, contents));
        }
    }
    Ok(entries)
}

fn svg_body(name: &str, svg: &str, style: &Style) -> Result<String> {
    // lucide's files start with a licence comment, so look for `<svg` rather than `>`
    let open_start = svg
        .find("<svg")
        .ok_or_else(|| format!("{name}: no <svg> tag"))?;
    let open_end = open_start
        + svg[open_start..]
            .find('>')
            .ok_or_else(|| format!("{name}: unterminated <svg> tag"))?;
    let close = svg
        .rfind("</svg>")
        .ok_or_else(|| format!("{name}: no closing tag"))?;
    let (open, inner) = (&svg[open_start..open_end], &svg[open_end + 1..close]);

    for (attribute, value) in [
        ("viewBox", style.view_box),
        ("fill", style.fill),
        ("stroke", style.stroke),
        ("stroke-width", style.stroke_width),
        ("stroke-linecap", style.stroke_linecap),
        ("stroke-linejoin", style.stroke_linejoin),
    ] {
        let expected = format!("{attribute}=\"{value}\"");
        if !open.contains(&expected) {
            return Err(format!("{name}: expected {expected} in the <svg> tag").into());
        }
    }

    let body = inner
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace(" />", "/>");
    if body.is_empty() {
        return Err(format!("{name}: empty icon").into());
    }
    Ok(body)
}

// `Loader2Icon` -> `loader-2`
fn upstream_name(react_name: &str, library: &Library) -> String {
    let name = react_name
        .strip_prefix(library.react_prefix)
        .unwrap_or(react_name);
    let name = name.strip_suffix(library.react_suffix).unwrap_or(name);
    let chars: Vec<char> = name.chars().collect();
    let mut out = String::new();
    for (index, &char) in chars.iter().enumerate() {
        let previous = index.checked_sub(1).map(|i| chars[i]);
        let boundary = match previous {
            None => false,
            Some(previous) => {
                (char.is_ascii_uppercase() && !previous.is_ascii_uppercase())
                    || (char.is_ascii_digit() && previous.is_ascii_alphabetic())
                    || (char.is_ascii_uppercase()
                        && previous.is_ascii_uppercase()
                        && chars.get(index + 1).is_some_and(char::is_ascii_lowercase))
            }
        };
        if boundary {
            out.push('-');
        }
        out.extend(char.to_lowercase());
    }
    out
}

fn icons_crate() -> PathBuf {
    workspace_root().join("crates").join("leptos-kit-icons")
}

fn constant_name(name: &str) -> String {
    name.to_uppercase().replace('-', "_")
}
